"""Paper figure and LaTeX table for the 256-case ImageNet inpainting study.

    uv run -m experiments.imagenet_inpainting_paper

Reads the evaluated study (``--stage evaluate`` writes ``results.json``)
and writes ``plots/figures/imagenet_inpainting_comparison.{png,pdf}`` and
``plots/imagenet_inpainting.tex``, a complete ``table`` float that pastes
into the paper (``booktabs`` and the paper's ``\\sci``/``\\scib`` macros).
"""

import argparse
import json
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from experiments import imagenet_inpainting_gallery as gallery
from experiments.imagenet_inpainting_study import load_sample

# Paper order: baselines as in Table 1, then ours.
ORDER = ("pcfm", "pigdm", "opc", "dps", "ldf")
FIGURE_LABELS = {"pcfm": "PCFM", "pigdm": r"$\Pi$GDM", "opc": "OPC",
                 "dps": "DPS", "ldf": "LDF (ours)"}
TABLE_LABELS = {
    "pcfm": "PCFM\n% ~\\citep{utkarsh2025pcfm}\n",
    "pigdm": "$\\Pi$GDM\n% ~\\citep{pokle2024training}\n",
    "opc": "OPC\n% ~\\citep{peng2024improving}\n",
    "dps": "DPS\n% ~\\citep{chung2023dps}\n",
    "ldf": "LDF (ours)",
}
VIOLATION_THRESHOLD = 1e-6  # as in Table 1: near single-precision round-off

# Drawn at print size (ICLR \textwidth, inches); STIX matches Times.
TEXT_WIDTH = 5.5
RC = {
    "font.family": "serif", "font.serif": ["STIXGeneral"],
    "mathtext.fontset": "stix", "font.size": 8, "axes.titlesize": 8,
    "axes.titlepad": 3, "axes.labelsize": 8, "axes.labelpad": 2,
    "axes.linewidth": 0.4,
}


def ordered(rows):
    by_method = {r["method"]: r for r in rows}
    return [by_method[m] for m in ORDER if m in by_method]


def figure(root, report, output):
    """Reference, observed input, and every method's output per case.

    The cases are the study's first five planned cases, shown unselected.
    Outputs are the raw whole images (no compositing), clipped for display.
    """
    plan = report["plan"]
    methods = [r["method"] for r in ordered(report["rows"])]
    cases = [c for c in plan["cases"] if c["id"] in plan["representative_ids"]]
    columns = ["Reference", "Masked input",
               *(FIGURE_LABELS[m] for m in methods)]
    gap = 0.04  # inches between panels
    side = (TEXT_WIDTH - gap * (len(columns) - 1)) / len(columns)
    title = 0.16
    with plt.rc_context(RC):
        fig = plt.figure(figsize=(TEXT_WIDTH,
                                  title + len(cases) * side
                                  + (len(cases) - 1) * gap))
        height = fig.get_figheight()
        for row, case in enumerate(cases):
            reference, _ = load_sample(root, plan, case, "references")
            observed = gallery.observed_mask(case)
            masked = np.where(observed[..., None], reference, 0.5)
            images = [reference, masked]
            for method in methods:
                images.append(load_sample(root, plan, case, method)[0])
            for col, image in enumerate(images):
                left = col * (side + gap) / TEXT_WIDTH
                bottom = 1 - (title + row * (side + gap) + side) / height
                ax = fig.add_axes((left, bottom, side / TEXT_WIDTH,
                                   side / height))
                ax.imshow(np.clip(image, 0, 1), interpolation="lanczos")
                ax.set_xticks([])
                ax.set_yticks([])
                for spine in ax.spines.values():
                    spine.set_visible(False)
                if row == 0:
                    ax.set_title(columns[col])
        output.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(output.with_suffix(".png"), dpi=600)
        fig.savefig(output.with_suffix(".pdf"), dpi=300)
        plt.close(fig)


def sci(value, bold=False):
    mantissa, exponent = f"{value:.1e}".split("e")
    macro = r"\scib" if bold else r"\sci"
    return f"{macro}{{{mantissa}}}{{{int(exponent)}}}"


def table(report):
    """Methods as rows; FID and KID for the whole image and the hole."""
    rows = ordered(report["rows"])
    paired = rows[0]["paired_n"]
    planned = rows[0]["planned"]
    metrics = [("fid_full", 1, "{:.1f}"), ("fid_hole", 1, "{:.1f}"),
               ("paired_kid_full", 1000, "{:.1f}"),
               ("paired_kid_hole", 1000, "{:.1f}")]
    best = {key: min(scale * r[key] for r in rows) for key, scale, _ in metrics}
    lines = [
        "% Generated by experiments/imagenet_inpainting_paper.py from",
        "% plots/imagenet_study_256/results.json.",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r"& \multicolumn{2}{c}{FID $\downarrow$}"
        r" & \multicolumn{2}{c}{KID $\times 10^3$ $\downarrow$}"
        r" & & \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Method & Full & Hole & Full & Hole & Viol. & Time (s) \\",
        r"\midrule",
    ]
    for r in rows:
        cells = []
        for key, scale, fmt in metrics:
            value = scale * r[key]
            text = fmt.format(value)
            if text == fmt.format(best[key]):
                text = rf"\textbf{{{text}}}"
            cells.append(text)
        cells.append(sci(r["observed_mae"],
                         bold=r["observed_mae"] < VIOLATION_THRESHOLD))
        seconds = r["seconds_median"]
        cells.append("---" if seconds is None else f"{seconds:.1f}")
        # Citation comments follow the label, as in Table 1.
        label, _, comment = TABLE_LABELS[r["method"]].partition("\n")
        if r["successful"] < r["planned"]:
            label += r"$^\ddagger$"
        name = f"{label}\n{comment}" if comment else label
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
    failures = [
        f"{FIGURE_LABELS[r['method']]} ({r['planned'] - r['successful']})"
        for r in rows if r["successful"] < r["planned"]
    ]
    caption = (
        "Image inpainting with the pretrained class-conditional JiT-H/32 "
        f"flow model on {planned} "
        r"$512\times512$ images, each with a random $192\times192$ "
        "missing square. Reference images are independent samples from the "
        "same model (class ``lakeside''). FID and KID compare outputs "
        "with the reference "
        "images over the whole image and over the missing region (hole), "
        f"on the {paired} cases where every method succeeded. KID is "
        "paired: matched reference/output pairs are excluded, so it can be "
        "negative. Viol. is the mean absolute error on observed pixels "
        "(values in $[0, 1]$); Time is the median per image on one RTX 5090. "
        "Bold marks the best value in each column."
    )
    if failures:
        caption += (r" $^\ddagger$Numerical failures (excluded): "
                    + ", ".join(failures) + ".")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        rf"\caption{{{caption}}}",
        r"\label{tab:inpainting}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--study",
                        default="results/imagenet_study_256_selected")
    parser.add_argument("--report", default="plots/imagenet_study_256")
    parser.add_argument("--figure",
                        default="plots/figures/imagenet_inpainting_comparison")
    parser.add_argument("--table", default="plots/imagenet_inpainting.tex")
    args = parser.parse_args()
    report = json.loads((Path(args.report) / "results.json").read_text())
    if not all(math.isfinite(r["fid_hole"]) for r in report["rows"]):
        raise ValueError("Incomplete report")
    Path(args.table).write_text(table(report))
    print(Path(args.table).read_text())
    figure(Path(args.study), report, Path(args.figure))
    print(f"wrote {args.figure}.png/.pdf and {args.table}")


if __name__ == "__main__":
    main()
