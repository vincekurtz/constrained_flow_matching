import torch
from torch.utils.data import Dataset


class ObstaclePathDataset(Dataset):
    """Wiggly 2D point-mass paths from a fixed start to a fixed goal.

    Each sample is a sequence of ``num_waypoints`` interior waypoints

        p_1, ..., p_T,

    describing the path of a point-mass robot. The start and goal positions are
    the same for every sample, so they are not part of the data: the full path
    is ``[start, p_1, ..., p_T, goal]``.

    Paths are generated by perturbing the straight line from start to goal with
    a random smooth (Fourier) wiggle, then running a few gradient steps to push
    the path out of a randomly sampled set of circular obstacles. The obstacles
    are *discarded* afterwards, so the dataset is unconditional: it is a
    distribution over smooth, wiggly, start-to-goal paths that detour in all
    sorts of directions, with no obstacle information attached.
    """

    def __init__(
        self,
        num_samples: int = 4096,
        num_waypoints: int = 24,
        start: tuple = (-1.0, 0.0),
        goal: tuple = (1.0, 0.0),
        num_obstacles: int = 2,
        obstacle_radius_range: tuple = (0.15, 0.35),
        clearance: float = 0.05,
        wiggle_scale: float = 0.4,
        num_modes: int = 3,
        max_step_ratio: float = 3.0,
        seed: int = 0,
    ):
        """Create a dataset of obstacle-avoiding point-mass paths.

        Args:
            num_samples: Number of paths in the dataset.
            num_waypoints: Number of interior waypoints T per path.
            start: Fixed start position, shared by all paths.
            goal: Fixed goal position, shared by all paths.
            num_obstacles: Number of random obstacles used to shape each path.
            obstacle_radius_range: (min, max) radius of the random obstacles.
            clearance: Extra margin kept between the path and each obstacle.
            wiggle_scale: Magnitude of the random Fourier perturbation, mostly
                normal to the straight line from start to goal.
            num_modes: Number of Fourier modes in the random perturbation.
            max_step_ratio: Reject paths with a step longer than this multiple
                of the straight-line waypoint spacing. Pushing a waypoint out
                of an obstacle occasionally leaves a long jump behind, and
                those paths are not worth learning from.
            seed: Random seed for reproducibility.
        """
        super().__init__()
        self.num_samples = num_samples
        self.num_waypoints = num_waypoints
        self.start = torch.tensor(start, dtype=torch.float32)
        self.goal = torch.tensor(goal, dtype=torch.float32)
        self.num_obstacles = num_obstacles
        self.obstacle_radius_range = obstacle_radius_range
        self.clearance = clearance
        self.wiggle_scale = wiggle_scale
        self.num_modes = num_modes
        self.max_step_ratio = max_step_ratio
        self.seed = seed
        self.data = self._generate_data()

    def full_path(self, waypoints: torch.Tensor) -> torch.Tensor:
        """Prepend the start and append the goal to a batch of waypoints.

        Args:
            waypoints: Interior waypoints, shape ``(..., T, 2)``.

        Returns:
            The full path, shape ``(..., T + 2, 2)``.
        """
        lead = waypoints.shape[:-2]
        start = self.start.expand(*lead, 1, 2)
        goal = self.goal.expand(*lead, 1, 2)
        return torch.cat([start, waypoints, goal], dim=-2)

    def _straight_line(self) -> torch.Tensor:
        """Interior waypoints of the straight path from start to goal."""
        s = torch.arange(1, self.num_waypoints + 1) / (self.num_waypoints + 1)
        return self.start + s[:, None] * (self.goal - self.start)

    def _sample_obstacles(self, num_paths: int) -> tuple:
        """Sample obstacles that sit in the way of the straight-line path.

        Returns:
            centers: Obstacle centers, shape ``(num_paths, M, 2)``.
            radii: Obstacle radii, shape ``(num_paths, M)``.
        """
        shape = (num_paths, self.num_obstacles)
        r_min, r_max = self.obstacle_radius_range
        radii = r_min + (r_max - r_min) * torch.rand(shape)

        # Centers are placed near the straight line from start to goal, so the
        # obstacles are actually in the way and force an interesting detour.
        s = 0.15 + 0.7 * torch.rand(shape)
        along = self.start + s[..., None] * (self.goal - self.start)
        offset = 0.35 * (2 * torch.rand(shape + (2,)) - 1)
        return along + offset, radii

    def _random_wiggle(self, num_paths: int) -> torch.Tensor:
        """Smooth random perturbations that vanish at both endpoints."""
        # Interior waypoints are at s = 1/(T+1), ..., T/(T+1) along the path.
        s = torch.arange(1, self.num_waypoints + 1) / (self.num_waypoints + 1)
        k = torch.arange(1, self.num_modes + 1)

        # sin(k * pi * s) is zero at s = 0 and s = 1, so the endpoints of the
        # path stay put. Higher modes get smaller amplitudes.
        basis = torch.sin(torch.pi * s[:, None] * k[None, :])  # (T, K)
        amps = torch.randn(num_paths, self.num_modes, 2) / k[:, None] ** 1.5

        # Wiggle mostly sideways: a large tangential component would make the
        # robot double back on itself, which is not a plausible path.
        tangent = (self.goal - self.start) / torch.linalg.norm(
            self.goal - self.start
        )
        normal = torch.stack([-tangent[1], tangent[0]])
        directions = torch.stack([0.15 * tangent, normal])  # (2, 2)
        return self.wiggle_scale * (basis @ amps @ directions)

    def _collision_points(self, waypoints: torch.Tensor) -> torch.Tensor:
        """Waypoints plus segment midpoints, where collisions are checked.

        Checking the midpoints as well stops a path from cutting a corner
        between two consecutive waypoints.
        """
        path = self.full_path(waypoints)
        mids = 0.5 * (path[..., :-1, :] + path[..., 1:, :])
        return torch.cat([path, mids], dim=-2)

    def _penetration(
        self,
        waypoints: torch.Tensor,
        centers: torch.Tensor,
        radii: torch.Tensor,
        clearance: float,
    ) -> torch.Tensor:
        """How far each collision point pokes into each obstacle."""
        pts = self._collision_points(waypoints)  # (N, P, 2)
        deltas = pts[:, :, None, :] - centers[:, None, :, :]  # (N, P, M, 2)
        dists = torch.linalg.norm(deltas, dim=-1)  # (N, P, M)
        return torch.relu(radii[:, None, :] + clearance - dists)

    def _optimize_paths(
        self,
        waypoints: torch.Tensor,
        centers: torch.Tensor,
        radii: torch.Tensor,
        num_steps: int = 150,
    ) -> torch.Tensor:
        """Push a batch of paths out of their obstacles, keeping them smooth.

        The cost decouples across paths, so optimizing the whole batch jointly
        is the same as optimizing each path on its own, only much faster.
        """
        p = waypoints.clone().requires_grad_(True)
        opt = torch.optim.Adam([p], lr=0.02)

        for _ in range(num_steps):
            opt.zero_grad()
            path = self.full_path(p)

            penetration = self._penetration(p, centers, radii, self.clearance)
            obstacle_cost = torch.sum(penetration**2)

            # Second differences penalize kinks without flattening the wiggle.
            accel = path[:, 2:] - 2 * path[:, 1:-1] + path[:, :-2]
            smooth_cost = torch.sum(accel**2)

            # Squared step lengths keep the waypoints evenly spaced.
            steps = path[:, 1:] - path[:, :-1]
            length_cost = torch.sum(steps**2)

            cost = 100.0 * obstacle_cost + 2.0 * smooth_cost + 0.2 * length_cost
            cost.backward()
            opt.step()

        return p.detach()

    def _generate_data(self) -> torch.Tensor:
        torch.random.manual_seed(self.seed)
        line = self._straight_line()

        paths = []
        num_found = 0
        attempts = 0
        while num_found < self.num_samples and attempts < 20:
            attempts += 1
            num_needed = self.num_samples - num_found
            centers, radii = self._sample_obstacles(num_needed)
            waypoints = line + self._random_wiggle(num_needed)
            waypoints = self._optimize_paths(waypoints, centers, radii)

            # Reject the rare path that the optimizer failed to free, and
            # any path left with an implausibly long jump between waypoints.
            penetration = self._penetration(waypoints, centers, radii, 0.0)
            collision_free = torch.amax(penetration, dim=(1, 2)) <= 0.0

            full = self.full_path(waypoints)
            steps = torch.linalg.norm(full[:, 1:] - full[:, :-1], dim=-1)
            spacing = torch.linalg.norm(self.goal - self.start) / (
                self.num_waypoints + 1
            )
            smooth = torch.amax(steps, dim=1) <= self.max_step_ratio * spacing

            keep = collision_free & smooth
            paths.append(waypoints[keep])
            num_found += int(keep.sum())

        if num_found < self.num_samples:
            raise RuntimeError(
                f"Only generated {num_found}/{self.num_samples} paths in "
                f"{attempts} rounds."
            )

        return torch.cat(paths, dim=0)

    def __len__(self):
        return self.num_samples

    def __getitem__(self, idx):
        return self.data[idx]


if __name__ == "__main__":
    # Make a quick plot to visualize the dataset
    import matplotlib.pyplot as plt

    dataset = ObstaclePathDataset(num_samples=512)
    paths = dataset.full_path(dataset.data).numpy()

    plt.axes().set_aspect("equal")
    for path in paths:
        plt.plot(path[:, 0], path[:, 1], "C0-", alpha=0.15, lw=1)
    plt.plot(*dataset.start, "go", ms=10, label="start")
    plt.plot(*dataset.goal, "r*", ms=14, label="goal")
    plt.title("Obstacle Path Training Data")

    plt.xlabel("x")
    plt.ylabel("y")
    plt.legend()
    plt.grid()
    plt.tight_layout()
    plt.show()
