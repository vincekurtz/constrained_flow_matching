import torch
from torch.utils.data import Dataset


def bezier_spline(knots: torch.Tensor, num_sub: int) -> torch.Tensor:
    """Evaluate a cubic Bezier spline passing through the given knots.

    Consecutive knots are joined by a cubic Bezier segment whose control
    points are set from Catmull-Rom tangents,

        m_i = (P_{i+1} - P_{i-1}) / 2,
        B_0 = P_i,  B_1 = P_i + m_i / 3,
        B_3 = P_{i+1},  B_2 = P_{i+1} - m_{i+1} / 3,

    (one-sided differences at the ends). The result interpolates every knot
    and is C1 continuous, so the path is smooth no matter where the knots
    land.

    Args:
        knots: Knot positions, shape ``(..., N, 2)``.
        num_sub: Number of samples per segment.

    Returns:
        Points along the spline, shape ``(..., num_sub * (N - 1) + 1, 2)``.
    """
    # Catmull-Rom tangents, with one-sided differences at the two ends.
    interior = 0.5 * (knots[..., 2:, :] - knots[..., :-2, :])
    first = knots[..., 1:2, :] - knots[..., 0:1, :]
    last = knots[..., -1:, :] - knots[..., -2:-1, :]
    tangents = torch.cat([first, interior, last], dim=-2)

    # Bezier control points of each segment, shape (..., N - 1, 2).
    b0 = knots[..., :-1, :]
    b3 = knots[..., 1:, :]
    b1 = b0 + tangents[..., :-1, :] / 3.0
    b2 = b3 - tangents[..., 1:, :] / 3.0

    # Bernstein basis, evaluated at num_sub points per segment.
    u = torch.arange(num_sub, dtype=knots.dtype) / num_sub
    u = u.reshape((1,) * (knots.dim() - 1) + (num_sub, 1))
    points = (
        (1 - u) ** 3 * b0[..., None, :]
        + 3 * (1 - u) ** 2 * u * b1[..., None, :]
        + 3 * (1 - u) * u**2 * b2[..., None, :]
        + u**3 * b3[..., None, :]
    )

    points = points.reshape(knots.shape[:-2] + (-1, 2))
    return torch.cat([points, knots[..., -1:, :]], dim=-2)


class ObstaclePathDataset(Dataset):
    """Wiggly 2D point-mass paths from a fixed start to a fixed goal.

    Each sample is a sequence of ``num_knots`` interior knots

        p_1, ..., p_T,

    defining the path of a point-mass robot. The robot follows the cubic
    Bezier spline through ``[start, p_1, ..., p_T, goal]``, so the path is
    smooth by construction and the knots are the only decision variables. The
    start and goal are the same for every sample and so are not part of the
    data.

    Paths are generated by perturbing the straight line from start to goal with
    a random smooth (Fourier) wiggle, then running a few gradient steps to push
    the spline out of a randomly sampled set of circular obstacles. The
    obstacles are *discarded* afterwards, so the dataset is unconditional: it
    is a distribution over smooth, wiggly, start-to-goal paths that detour in
    all sorts of directions, with no obstacle information attached.
    """

    def __init__(
        self,
        num_samples: int = 4096,
        num_knots: int = 10,
        start: tuple = (-1.0, 0.0),
        goal: tuple = (1.0, 0.0),
        num_obstacles: int = 2,
        obstacle_radius_range: tuple = (0.15, 0.35),
        clearance: float = 0.05,
        wiggle_scale: float = 0.4,
        num_modes: int = 3,
        max_step_ratio: float = 2.5,
        spline_samples: int = 8,
        seed: int = 0,
    ):
        """Create a dataset of obstacle-avoiding point-mass paths.

        Args:
            num_samples: Number of paths in the dataset.
            num_knots: Number of interior spline knots T per path.
            start: Fixed start position, shared by all paths.
            goal: Fixed goal position, shared by all paths.
            num_obstacles: Number of random obstacles used to shape each path.
            obstacle_radius_range: (min, max) radius of the random obstacles.
            clearance: Extra margin kept between the path and each obstacle.
            wiggle_scale: Magnitude of the random Fourier perturbation, mostly
                normal to the straight line from start to goal.
            num_modes: Number of Fourier modes in the random perturbation.
            max_step_ratio: Reject paths with a knot spacing longer than this
                multiple of the straight-line spacing. Pushing a knot out of
                an obstacle occasionally leaves a long jump behind, and those
                paths are not worth learning from.
            spline_samples: Samples per spline segment used when checking
                obstacle collisions during data generation.
            seed: Random seed for reproducibility.
        """
        super().__init__()
        self.num_samples = num_samples
        self.num_knots = num_knots
        self.start = torch.tensor(start, dtype=torch.float32)
        self.goal = torch.tensor(goal, dtype=torch.float32)
        self.num_obstacles = num_obstacles
        self.obstacle_radius_range = obstacle_radius_range
        self.clearance = clearance
        self.wiggle_scale = wiggle_scale
        self.num_modes = num_modes
        self.max_step_ratio = max_step_ratio
        self.spline_samples = spline_samples
        self.seed = seed
        self.data = self._generate_data()

    def full_knots(self, knots: torch.Tensor) -> torch.Tensor:
        """Prepend the start and append the goal to a batch of interior knots.

        Args:
            knots: Interior knots, shape ``(..., T, 2)``.

        Returns:
            The full knot sequence, shape ``(..., T + 2, 2)``.
        """
        lead = knots.shape[:-2]
        start = self.start.expand(*lead, 1, 2)
        goal = self.goal.expand(*lead, 1, 2)
        return torch.cat([start, knots, goal], dim=-2)

    def path(self, knots: torch.Tensor, num_sub: int = None) -> torch.Tensor:
        """The Bezier spline the robot actually follows, given interior knots.

        Args:
            knots: Interior knots, shape ``(..., T, 2)``.
            num_sub: Samples per spline segment. Defaults to
                ``spline_samples``.

        Returns:
            Points along the path, shape ``(..., num_sub * (T + 1) + 1, 2)``.
        """
        if num_sub is None:
            num_sub = self.spline_samples
        return bezier_spline(self.full_knots(knots), num_sub)

    def _straight_line(self) -> torch.Tensor:
        """Interior knots of the straight path from start to goal."""
        s = torch.arange(1, self.num_knots + 1) / (self.num_knots + 1)
        return self.start + s[:, None] * (self.goal - self.start)

    def _sample_obstacles(self, num_paths: int) -> tuple:
        """Sample obstacles that sit in the way of the straight-line path.

        Returns:
            centers: Obstacle centers, shape ``(num_paths, M, 2)``.
            radii: Obstacle radii, shape ``(num_paths, M)``.
        """
        shape = (num_paths, self.num_obstacles)
        r_min, r_max = self.obstacle_radius_range
        radii = r_min + (r_max - r_min) * torch.rand(shape)

        # Centers are placed near the straight line from start to goal, so the
        # obstacles are actually in the way and force an interesting detour.
        s = 0.15 + 0.7 * torch.rand(shape)
        along = self.start + s[..., None] * (self.goal - self.start)
        offset = 0.35 * (2 * torch.rand(shape + (2,)) - 1)
        return along + offset, radii

    def _random_wiggle(self, num_paths: int) -> torch.Tensor:
        """Smooth random perturbations that vanish at both endpoints."""
        # Interior knots are at s = 1/(T+1), ..., T/(T+1) along the path.
        s = torch.arange(1, self.num_knots + 1) / (self.num_knots + 1)
        k = torch.arange(1, self.num_modes + 1)

        # sin(k * pi * s) is zero at s = 0 and s = 1, so the endpoints of the
        # path stay put. Higher modes get smaller amplitudes.
        basis = torch.sin(torch.pi * s[:, None] * k[None, :])  # (T, K)
        amps = torch.randn(num_paths, self.num_modes, 2) / k[:, None] ** 1.5

        # Wiggle mostly sideways: a large tangential component would make the
        # robot double back on itself, which is not a plausible path.
        tangent = (self.goal - self.start) / torch.linalg.norm(
            self.goal - self.start
        )
        normal = torch.stack([-tangent[1], tangent[0]])
        directions = torch.stack([0.15 * tangent, normal])  # (2, 2)
        return self.wiggle_scale * (basis @ amps @ directions)

    def _penetration(
        self,
        knots: torch.Tensor,
        centers: torch.Tensor,
        radii: torch.Tensor,
        clearance: float,
    ) -> torch.Tensor:
        """How far the spline pokes into each obstacle."""
        pts = self.path(knots)  # (N, P, 2)
        deltas = pts[:, :, None, :] - centers[:, None, :, :]  # (N, P, M, 2)
        dists = torch.linalg.norm(deltas, dim=-1)  # (N, P, M)
        return torch.relu(radii[:, None, :] + clearance - dists)

    def _optimize_paths(
        self,
        knots: torch.Tensor,
        centers: torch.Tensor,
        radii: torch.Tensor,
        num_steps: int = 150,
    ) -> torch.Tensor:
        """Push a batch of paths out of their obstacles, keeping them tidy.

        The cost decouples across paths, so optimizing the whole batch jointly
        is the same as optimizing each path on its own, only much faster.
        """
        p = knots.clone().requires_grad_(True)
        opt = torch.optim.Adam([p], lr=0.02)

        for _ in range(num_steps):
            opt.zero_grad()
            full = self.full_knots(p)

            penetration = self._penetration(p, centers, radii, self.clearance)
            obstacle_cost = torch.sum(penetration**2)

            # The spline is smooth on its own; these terms only keep the knots
            # from bunching up or zig-zagging as they are pushed around.
            accel = full[:, 2:] - 2 * full[:, 1:-1] + full[:, :-2]
            smooth_cost = torch.sum(accel**2)

            steps = full[:, 1:] - full[:, :-1]
            length_cost = torch.sum(steps**2)

            cost = 100.0 * obstacle_cost + 2.0 * smooth_cost + 0.2 * length_cost
            cost.backward()
            opt.step()

        return p.detach()

    def _generate_data(self) -> torch.Tensor:
        torch.random.manual_seed(self.seed)
        line = self._straight_line()
        spacing = torch.linalg.norm(self.goal - self.start) / (
            self.num_knots + 1
        )

        paths = []
        num_found = 0
        attempts = 0
        while num_found < self.num_samples and attempts < 20:
            attempts += 1
            num_needed = self.num_samples - num_found
            centers, radii = self._sample_obstacles(num_needed)
            knots = line + self._random_wiggle(num_needed)
            knots = self._optimize_paths(knots, centers, radii)

            # Reject the rare path that the optimizer failed to free, and any
            # path left with an implausibly long jump between knots.
            penetration = self._penetration(knots, centers, radii, 0.0)
            collision_free = torch.amax(penetration, dim=(1, 2)) <= 0.0

            full = self.full_knots(knots)
            steps = torch.linalg.norm(full[:, 1:] - full[:, :-1], dim=-1)
            tidy = torch.amax(steps, dim=1) <= self.max_step_ratio * spacing

            keep = collision_free & tidy
            paths.append(knots[keep])
            num_found += int(keep.sum())

        if num_found < self.num_samples:
            raise RuntimeError(
                f"Only generated {num_found}/{self.num_samples} paths in "
                f"{attempts} rounds."
            )

        return torch.cat(paths, dim=0)

    def __len__(self):
        return self.num_samples

    def __getitem__(self, idx):
        return self.data[idx]


